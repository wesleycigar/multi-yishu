# ========== 五、五行生克 ==========
WUXING_SHENG = {"木": "火", "火": "土", "土": "金", "金": "水", "水": "木"}  # 我生者
WUXING_KE = {"木": "土", "土": "水", "水": "火", "火": "金", "金": "木"}  # 我克者

# ========== 六、六亲定义（以卦宫五行为"我"） ==========
def get_liuqin(wo_wuxing, zhi_wuxing):
    """根据卦宫五行和爻支五行，返回六亲"""
    if zhi_wuxing == wo_wuxing:
        return "兄弟"
    if WUXING_SHENG[wo_wuxing] == zhi_wuxing:  # 我生者
        return "子孙"
    if WUXING_SHENG[zhi_wuxing] == wo_wuxing:  # 生我者
        return "父母"
    if WUXING_KE[wo_wuxing] == zhi_wuxing:  # 我克者
        return "妻财"
    if WUXING_KE[zhi_wuxing] == wo_wuxing:  # 克我者
        return "官鬼"
    return "?"

# ========== 七、六神（按日天干起） ==========
LIUSHEN_START = {
    "甲": "青龙", "乙": "青龙",
    "丙": "朱雀", "丁": "朱雀",
    "戊": "勾陈",
    "己": "螣蛇",
    "庚": "白虎", "辛": "白虎",
    "壬": "玄武", "癸": "玄武",
}
LIUSHEN_CYCLE = ["青龙", "朱雀", "勾陈", "螣蛇", "白虎", "玄武"]

def get_liushen(ri_gan, yao_index):
    """根据日天干和爻位(0=初爻)返回六神"""
    start = LIUSHEN_START[ri_gan]
    start_idx = LIUSHEN_CYCLE.index(start)
    return LIUSHEN_CYCLE[(start_idx + yao_index) % 6]

# ========== 八、十神定义（八字用，以日干为"我"） ==========
def get_shishen(ri_gan, other_gan):
    """
    十神：比肩、劫财、食神、伤官、偏财、正财、七杀、正官、偏印、正印
    """
    wo = TIANGAN[ri_gan]
    other = TIANGAN[other_gan]
    wo_wx, wo_yy = wo["五行"], wo["阴阳"]
    ot_wx, ot_yy = other["五行"], other["阴阳"]
    same_yy = (wo_yy == ot_yy)
    
    if ot_wx == wo_wx:
        return "比肩" if same_yy else "劫财"
    if WUXING_SHENG[wo_wx] == ot_wx:  # 我生
        return "食神" if same_yy else "伤官"
    if WUXING_KE[wo_wx] == ot_wx:  # 我克
        return "偏财" if same_yy else "正财"
    if WUXING_KE[ot_wx] == wo_wx:  # 克我
        return "七杀" if same_yy else "正官"
    if WUXING_SHENG[ot_wx] == wo_wx:  # 生我
        return "偏印" if same_yy else "正印"
    return "?"

