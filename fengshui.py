def get_minggua(birth_year, gender="男"):
    """按出生年+性别算八宅命卦。返回 (命卦, 东四/西四命)。"""
    two = birth_year % 100
    if gender == "女":
        n = (two - 4) % 9
    else:
        n = (100 - two) % 9
    if n == 0:
        n = 9
    mg = MINGGUA_GONG[n]
    if mg == "中":  # 中宫寄宫：男寄坤、女寄艮
        mg = "坤" if gender == "男" else "艮"
    return mg, DONGXI[mg]


def fengshui_advice(birth_year=None, gender="男", seat=None, room_type="客厅"):
    """
    风水布局建议（八宅起盘）
    birth_year: 屋主出生年；gender: 性别；seat: 宅坐向（如"北"=坐北朝南，可选）
    """
    lines = []
    lines.append("=" * 60)
    lines.append("🏠 木雷易术引擎 · 风水八宅起盘")
    lines.append("=" * 60)

    lines.append(f"\n📋 【起盘信息】")
    lines.append(f"  屋主出生年：{birth_year or '未提供'}　性别：{gender}")
    lines.append(f"  宅之坐向：{seat or '未提供'}　空间：{room_type}")

    # 1. 命卦
    if birth_year:
        minggua, dongxi = get_minggua(birth_year, gender)
        lines.append(f"\n🧮 【屋主命卦】")
        lines.append(f"  命卦：{minggua}　属【{dongxi}】")
        lines.append(f"  宜居：{DONGXI_ZHAI[minggua]}（{dongxi}）之宅，纳吉气、避凶方")
        lines.append(f"  吉方（生气/延年/天医/伏位）：按命卦游年定，非固定八方")
    else:
        minggua = None

    # 2. 坐向 → 宅卦 + 宅命相配
    if seat:
        zhai_gua = FANG_MINGGUA.get(seat)
        if zhai_gua:
            zhai_dongxi = DONGXI_ZHAI[zhai_gua]
            lines.append(f"\n🏡 【宅卦与相配】")
            lines.append(f"  坐{seat} → 宅卦：{zhai_gua}（{zhai_dongxi}）")
            if minggua:
                ren = DONGXI[minggua]
                zhai_dx = "东四宅" if zhai_dongxi == "东四宅" else "西四宅"
                ren_dx = "东四宅" if ren == "东四命" else "西四宅"
                if zhai_dx == ren_dx:
                    lines.append(f"  ✅ 宅命相配：你{ren}，宅{zhai_dx}，五行相合，纳气佳")
                else:
                    lines.append(f"  ⚠️ 宅命不配：你{ren}却居{zhai_dx}，气场相拗，宜以门、床、灶方位化解")

    # 3. 八方吉凶（按命卦起游年）
    if minggua:
        lines.append(f"\n🧭 【八宅吉凶方位】（按命卦{minggua}起游年）")
        bazhai = BAZHAI_BY_MINGGUA[minggua]
        for direction in ("北", "东北", "东", "东南", "南", "西南", "西", "西北"):
            jx, star, mean = bazhai[direction]
            mark = "✅" if jx == "吉" else "❌"
            lines.append(f"  {mark} {direction}方（{star}）：{mean}")
        lines.append(f"  → 宜将大门、主卧、灶、神位置于吉方，厕所、杂物置于凶方")

    # 4. 各空间布局要点（结合命卦吉方提示）
    lines.append(f"\n🛋️ 【{room_type}布局要点】")
    lines.append(f"  1. 沙发/主位宜靠实墙（有靠山），背后勿对门、窗")
    lines.append(f"  2. 财位（入户门对角线）宜净亮，放绿植或聚宝盆")
    lines.append(f"  3. 横梁勿压沙发、餐桌（横梁压顶主压力）")
    lines.append(f"  4. 采光通风为先，明亮通透则气顺")
    if minggua:
        ji_fang = [d for d in ("北", "东北", "东", "东南", "南", "西南", "西", "西北")
                   if BAZHAI_BY_MINGGUA[minggua][d][0] == "吉"]
        lines.append(f"  5. 若可，将主要活动位朝向吉方（{ '、'.join(ji_fang) }）为佳")

    # 5. 化煞
    lines.append(f"\n🛡️ 【常见化煞方法】")
    lines.append(f"  • 穿堂煞（门对窗）：屏风或玄关遮挡")
    lines.append(f"  • 路冲煞（大门直对路）：石狮子或八卦镜")
    lines.append(f"  • 尖角煞（对尖角）：植物或泰山石敢当")
    lines.append(f"  • 横梁压顶：吊顶遮挡或放葫芦")

    lines.append(f"\n{'='*60}")
    lines.append(f"⚠️ 风水为传统环境学，命卦起盘与坐向相配为主，心正则气顺、事在人为")
    lines.append(f"{'='*60}")

    # D：佐证/白话/语料/溯源 增强
    try:
        from analysis_enhance import finalize
        mg_txt = minggua or "未知"
        lines = finalize(lines, "风水",
                         f"{room_type} 风水 八宅 {mg_txt}命 游年 坐向",
                         gua_names=["坎", "坤", "震", "巽", "乾", "兑", "艮", "离"],
                         brief=f"屋主{mg_txt}命卦，按八宅游年定吉凶方位，宜居命卦相配之宅，纳吉气避凶方。")
    except Exception:
        pass

    return "\n".join(lines)


