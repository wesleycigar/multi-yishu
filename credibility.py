#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
木雷易术引擎 · 可信度分级层（A–E）

对应《象数重构方案 V2》：把“能复算的 / 能溯源的 / 能回测的 / 只是类比 / 纯属推测”
分开标注，避免把形式同构升级成因果结论。

分级口径
  A  公理可验证数学：定义清晰、可独立复算的符号结构
  B  古籍可溯源：有明确典籍原文支撑的传统规则
  C  统计可回测：依赖经验权重，须以样本量与命中率标定
  D  类比启发：形式同构但无因果，只作理解框架
  E  推测：无可验证依据的假说

硬规则：D、E 级不得进入行动建议。
"""

LEVELS = [
    ("A", "公理可验证数学", "定义清晰、可独立复算的符号结构"),
    ("B", "古籍可溯源", "有明确典籍原文支撑的传统规则"),
    ("C", "统计可回测", "依赖经验权重，须以样本命中率标定"),
    ("D", "类比启发", "形式同构但无因果，仅供理解框架"),
    ("E", "推测", "无可验证依据的假说"),
]

# 六爻场景下各类主张的默认级别
CLAIMS = {
    "卦画编码": ("A", "阴阳→比特，六爻→0~63，错/综/互/变均可复算"),
    "纳甲装卦": ("B", "《京氏易传》纳甲法"),
    "世应六亲": ("B", "《增删卜易》《卜筮正宗》"),
    "用神取法": ("B", "《增删卜易·用神章》"),
    "月建日辰": ("B", "《卜筮正宗·月建章》"),
    "旬空": ("B", "《卜筮正宗》"),
    "生克制化": ("B", "五行生克，古籍通例"),
    "吉凶分值": ("C", "规则加权打分，需以历史卦例回测命中率"),
    "应期远近": ("C", "经验规则，样本尚未标定"),
    "五行↔控制论": ("D", "生克环与负反馈形式相似，非因果"),
    "64卦↔密码子": ("D", "组合数相同，无生物学对应"),
    "卦象↔具体人事": ("E", "象与事之间无实证因果链"),
}

ADVICE_FORBIDDEN = ("D", "E")


def level_of(name):
    """返回某类主张的 (级别, 说明)"""
    return CLAIMS.get(name, ("C", "经验规则，待回测"))


def grading_block(ben_gua="", yong="", score=None):
    """生成报告末尾的【溯源与主张分级】段（第六段），返回可 append 的行列表"""
    lines = ["", "📊 【溯源与主张分级】（A–E 可信度）"]
    for lv, title, desc in LEVELS:
        lines.append("  %s｜%s —— %s" % (lv, title, desc))

    used = []
    if ben_gua:
        used.append(("卦画编码", "本卦 %s 的编码与错/综/互/变" % ben_gua))
    if yong:
        used.append(("用神取法", "用神取「%s」" % yong))
    used.append(("月建日辰", "以月建日辰定旺衰"))
    used.append(("生克制化", "原神/忌神/仇神生克"))
    if score is not None:
        used.append(("吉凶分值", "综合评分 %s 判定吉凶" % score))
    used.append(("应期远近", "应期窗口"))

    lines.append("")
    lines.append("  本报告的判断来源：")
    for name, ctx in used:
        lv, note = level_of(name)
        lines.append("    [%s] %s —— %s；依据：%s" % (lv, ctx, name, note))

    lines.append("")
    lines.append("  本次未采用的 D/E 级内容：五行↔负反馈控制、64卦↔64密码子、卦象↔具体人事的因果——")
    lines.append("  这些只作理解框架，不作任何行动依据。")
    lines.append("  ⚠️ 硬规则：D、E 级不得进入行动建议。")
    return lines


def prompt_rules():
    """给 DeepSeek 的标签约束文本"""
    return """【可信度标签规则（必须遵守）】
A｜公理可验证数学（卦画编码、错/综/互/变等可复算结构）
B｜古籍可溯源（纳甲、世应六亲、用神、月建日辰、旬空、生克制化，须写明书名）
C｜统计可回测（吉凶分值、应期远近，需以卦例回测命中率标定，未标定前只说“倾向”）
D｜类比启发（五行↔控制论、64卦↔密码子等，只作理解框架）
E｜推测（象与具体人事的因果对应，无实证）

规则：
1. 每条判断后必须带级别标签，例如“用神旺相得月建生扶【B】”。
2. 【关键提醒】中的建议只能由 A/B/C 支撑；D、E 级只能出现在解释性文字中，不得写成行动依据。
3. 引古籍必须写书名，不得杜撰篇名或原文。
4. 涉及概率/时间的判断，说清是“规则倾向”而非“确定预测”。
"""


def advice_levels_ok(text):
    """检查一段建议是否只含 A/B/C 标签（若明显夹带 D/E 级说法则返回 False）"""
    bad = ["量子", "密码子", "DNA", "负反馈", "预言", "必然应验"]
    return not any(w in text for w in bad)


if __name__ == "__main__":
    for ln in grading_block("火天大有", "妻财", 0.62):
        print(ln)
